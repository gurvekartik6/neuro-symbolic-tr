
import json
import os
from pathlib import Path

from dotenv import load_dotenv
from fastapi import FastAPI, HTTPException
from fastapi.responses import HTMLResponse, StreamingResponse
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel, Field

from .gemini_service import GeminiService
from .schemas import TraceSubmission, CounterfactualRequest
from .store import save_run, get_run, list_runs
from .verification import verify_run, intervention_assessment


ROOT = Path(__file__).resolve().parent.parent
load_dotenv(ROOT / ".env")

app = FastAPI(
    title="NS-CR Research Lab",
    version="1.2.0",
    description="Gemini-assisted diagnosis with evidence-backed trace validation.",
)

app.mount(
    "/static",
    StaticFiles(directory=ROOT / "static"),
    name="static",
)


class PlanRequest(BaseModel):
    task: str = Field(min_length=10, max_length=6000)


class DiagnoseRequest(BaseModel):
    run_id: str
    issue: str = Field(default="", max_length=3000)


class RepairRequest(BaseModel):
    run_id: str


def service():
    try:
        return GeminiService()
    except RuntimeError as exc:
        raise HTTPException(status_code=503, detail=str(exc)) from exc


def _ensure_run(run_id):
    run = get_run(run_id)
    if not run:
        raise HTTPException(status_code=404, detail="Run not found.")
    return run


def _serialize_events(events) -> list[dict]:
    return [
        event.model_dump(mode="json")
        if hasattr(event, "model_dump")
        else event
        for event in events
    ]


def _sse(data: dict) -> str:
    """Encode one Server-Sent Event."""
    return f"data: {json.dumps(data, ensure_ascii=False)}\n\n"


@app.get("/", response_class=HTMLResponse)
def home():
    return (ROOT / "static" / "index.html").read_text(
        encoding="utf-8"
    )


@app.get("/api/health")
def health():
    key = os.getenv("GEMINI_API_KEY", "").strip()

    return {
        "status": "ok",
        "gemini_key_configured": bool(
            key and key != "replace_with_your_key"
        ),
        "model": os.getenv("GEMINI_MODEL", "gemini-3.8-flash"),
        "streaming": True,
        "causal_verification": (
            "evidence-backed; intervention requires user-recorded observations"
        ),
    }


@app.post("/api/plan")
def create_plan(req: PlanRequest):
    """Keep the original non-streaming endpoint for compatibility."""
    gemini = service()

    try:
        plan = gemini.plan(req.task)
        run_id = save_run(req.task, gemini.model, plan)

        return {
            "run_id": run_id,
            "model": gemini.model,
            "task": req.task,
            "plan": plan,
            "notice": (
                "Plan generated by Gemini. No real-world actions were executed."
            ),
        }

    except RuntimeError as exc:
        raise HTTPException(status_code=502, detail=str(exc)) from exc


@app.post("/api/plan/stream")
def create_plan_stream(req: PlanRequest):
    """
    Stream status messages and Gemini output chunks using SSE.
    The completed structured plan is saved only after validation succeeds.
    """

    def generate():
        try:
            gemini = GeminiService()

            yield _sse({
                "type": "status",
                "message": "Request accepted. Connecting to Gemini...",
            })

            for event in gemini.stream_plan(req.task):
                if event["type"] == "result":
                    plan = event["plan"]

                    run_id = save_run(
                        req.task,
                        gemini.model,
                        plan,
                    )

                    yield _sse({
                        "type": "complete",
                        "run_id": run_id,
                        "model": gemini.model,
                        "task": req.task,
                        "plan": plan,
                        "notice": (
                            "Plan generated by Gemini. No real-world "
                            "actions were executed."
                        ),
                    })

                else:
                    yield _sse(event)

        except Exception as exc:
            # The response has already started; report failures as SSE events.
            yield _sse({
                "type": "error",
                "message": str(exc),
            })

    return StreamingResponse(
        generate(),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache, no-transform",
            "X-Accel-Buffering": "no",
            "Connection": "keep-alive",
        },
    )


@app.post("/api/trace")
def submit_trace(req: TraceSubmission):
    run = _ensure_run(req.run_id)
    events = _serialize_events(req.events)

    if len({event["event_id"] for event in events}) != len(events):
        raise HTTPException(
            status_code=422,
            detail="event_id values must be unique within a trace.",
        )

    valid_steps = {
        step["id"] for step in run["plan"].get("steps", [])
    }

    unknown = sorted({
        event["step_id"]
        for event in events
        if event.get("step_id")
        and event["step_id"] not in valid_steps
    })

    report = verify_run(run["plan"], events)

    new_id = save_run(
        run["task"],
        run["model"],
        run["plan"],
        issue=run.get("issue", ""),
        trace=events,
        verification=report,
    )

    return {
        "run_id": new_id,
        "trace_event_count": len(events),
        "unknown_step_ids": unknown,
        "verification": report,
        "notice": (
            "Trace contains user-supplied evidence only. NS-CR did not "
            "execute or fabricate events."
        ),
    }


@app.post("/api/verify")
def verify(req: DiagnoseRequest):
    run = _ensure_run(req.run_id)

    if not run.get("trace"):
        raise HTTPException(
            status_code=400,
            detail="Add an actual execution trace before verification.",
        )

    report = verify_run(run["plan"], run["trace"])

    new_id = save_run(
        run["task"],
        run["model"],
        run["plan"],
        diagnosis=run.get("diagnosis"),
        repair=run.get("repair"),
        issue=run.get("issue", req.issue),
        trace=run["trace"],
        verification=report,
    )

    return {
        "run_id": new_id,
        "verification": report,
        "notice": (
            "Deterministic checks validate entered evidence only; "
            "they do not prove the evidence is complete or truthful."
        ),
    }


@app.post("/api/diagnose")
def diagnose(req: DiagnoseRequest):
    run = _ensure_run(req.run_id)
    trace = run.get("trace") or []

    verification = (
        verify_run(run["plan"], trace)
        if trace
        else {
            "trace_event_count": 0,
            "causal_conclusion": "undetermined",
            "notes": ["No execution trace was supplied."],
        }
    )

    if trace:
        gemini = service()

        try:
            diagnosis = gemini.diagnose(
                run["task"],
                run["plan"],
                trace,
                req.issue or run.get("issue", ""),
                verification,
            )
        except RuntimeError as exc:
            raise HTTPException(
                status_code=502,
                detail=str(exc),
            ) from exc

    else:
        diagnosis = {
            "candidate_step_id": None,
            "root_cause_hypothesis": (
                "Insufficient execution evidence to localize a root cause."
            ),
            "evidence": [],
            "alternative_causes": [],
            "confidence": 0.0,
            "repair_action": (
                "Record actual execution events and observations "
                "before requesting a diagnosis."
            ),
            "requires_human_confirmation": True,
            "limitations": [
                "No execution trace was supplied; the plan describes "
                "intent, not actual execution."
            ],
            "evidence_event_ids": [],
            "causal_status": "undetermined",
        }

    new_id = save_run(
        run["task"],
        run["model"],
        run["plan"],
        diagnosis=diagnosis,
        issue=req.issue,
        trace=trace or None,
        verification=verification,
    )

    return {
        "run_id": new_id,
        "source_run_id": req.run_id,
        "diagnosis": diagnosis,
        "verification": verification,
        "notice": (
            "A diagnosis is a hypothesis. Causal verification requires "
            "controlled evidence; model confidence is not proof."
        ),
    }


@app.post("/api/counterfactual")
def counterfactual(req: CounterfactualRequest):
    run = _ensure_run(req.run_id)

    known = {
        step["id"] for step in run["plan"].get("steps", [])
    }

    payload = req.model_dump(mode="json")
    assessment = intervention_assessment(payload, known)

    report = verify_run(
        run["plan"],
        run.get("trace") or [],
        causal_conclusion=assessment["status"],
    )

    result = {
        "intervention": payload,
        "assessment": assessment,
        "verification": report,
        "notice": (
            "This assesses reported intervention observations; NS-CR did "
            "not execute the intervention or independently authenticate its source."
        ),
    }

    new_id = save_run(
        run["task"],
        run["model"],
        run["plan"],
        diagnosis=run.get("diagnosis"),
        repair=run.get("repair"),
        issue=run.get("issue", ""),
        trace=run.get("trace"),
        verification={**report, "intervention_assessment": result},
    )

    return {"run_id": new_id, **result}


@app.post("/api/repair")
def repair(req: RepairRequest):
    run = _ensure_run(req.run_id)

    if not run.get("diagnosis"):
        raise HTTPException(
            status_code=400,
            detail="Diagnose the run before requesting a repair.",
        )

    gemini = service()

    try:
        repair_data = gemini.repair(
            run["task"],
            run["plan"],
            run["diagnosis"],
        )

        new_id = save_run(
            run["task"],
            run["model"],
            run["plan"],
            diagnosis=run["diagnosis"],
            repair=repair_data,
            issue=run.get("issue", ""),
            trace=run.get("trace"),
            verification=run.get("verification"),
        )

        return {
            "run_id": new_id,
            "repair": repair_data,
            "notice": (
                "Repair proposal only. It has been structurally validated "
                "but not executed or outcome-verified."
            ),
        }

    except RuntimeError as exc:
        raise HTTPException(status_code=502, detail=str(exc)) from exc


